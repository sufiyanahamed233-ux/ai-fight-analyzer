  if (score <= 4.4) return FIGHTER_MAP.curtis_blaydes;
  if (score <= 4.6) return FIGHTER_MAP.diego_lopes;
  if (score <= 4.8) return FIGHTER_MAP.dricus_du_plessis;
  if (score <= 5.0) return FIGHTER_MAP.gabriel_bonfim;
  if (score <= 5.2) return FIGHTER_MAP.ian_machado_garry;
