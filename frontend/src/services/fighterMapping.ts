  if (score <= 6.2) return FIGHTER_MAP.jamall_emmers;
  if (score <= 6.4) return FIGHTER_MAP.joanderson_brito;
  if (score <= 6.6) return FIGHTER_MAP.josh_hokit;
  if (score <= 6.8) return FIGHTER_MAP.khamzat_chimaev;
  if (score <= 7.0) return FIGHTER_MAP.kyoji_horiguchi;
  if (score <= 7.2) return FIGHTER_MAP.lerone_murphy;
  if (score <= 7.4) return FIGHTER_MAP.manel_kape;
